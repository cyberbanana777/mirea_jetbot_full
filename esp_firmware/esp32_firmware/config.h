float REF_TAU_S = 0.0;

// === Выбор регулятора и LADRC ===
// CTRL_MODE: 0 - feedforward + ПИ (как раньше), 1 - LADRC. Меняется командой $15 без перепрошивки,
// переключение на ходу безударное (скважность в момент переключения не скачет).
// По умолчанию LADRC (настроен на полу 29.10.2026: steptest s_l9.csv).
int CTRL_MODE = 1;
// LADRC первого порядка: модель колеса dv/dt = b0*u + f, где f - всё неизвестное (инерция, трение,
// мёртвая зона, нагрузка). Наблюдатель ESO оценивает v и f, закон u = (wc*(r - z1) - z2) / b0.
// ADRC_WC  - полоса контура, рад/с: отклик на уставку ~ 1/(s/wc + 1), то есть lambda = 1/wc
//            (5 рад/с ~ lambda 0.2 с, как у ПИ с общей lambda).
// ADRC_WO  - полоса наблюдателя, рад/с: обычно 3-5 * ADRC_WC. При такте 10 мс держать wo*dt <= 0.5
//            (wo <= 50); больше - шум скважности и раскачка из-за запаздывания измерения.
// ADRC_B0_L/R - ускорение колеса на единицу скважности, (м/с^2) на 1.0 = K / Tm. Здесь по калибровке
//            в воздухе: L 1.709/0.174, R 1.0945/0.143. Ошибиться лучше в большую сторону
//            (медленнее, но устойчиво); заниженное b0 с запаздыванием может раскачать контур.
// ADRC_FF  - прямая подача по калибровке feedforward ($11), наблюдатель оценивает остаток:
//            0 - нет (чистый LADRC: мёртвую зону и трение ESO находит сам после каждого старта),
//            1 - только мёртвая зона sign(r)*FF_DEADZONE,
//            2 - полный статический feedforward sign(r)*(FF_DEADZONE + FF_GAIN*|r|), как у ПИ.
//            Без прямой подачи старт с места на полу заметно медленнее (ESO "ищет" 0.3 скважности).
// Подобрано на полу (steptest, 29.10.2026): wc 9, wo 40 -> t90 ~280 мс на 1.2 об/с,
// перерегулирование 5-8 %, набег курса за ступеньку < 0.1 град. (wc 5 / wo 25 медленнее,
// wo 30 хуже синхронность колёс.)
float ADRC_WC = 9.0;
float ADRC_WO = 40.0;
float ADRC_B0_L = 9.82;
float ADRC_B0_R = 7.65;
float ADRC_FF = 2.0;

