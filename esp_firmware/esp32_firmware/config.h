const uint8_t PIN_R_B = 35;  // Правое колесо, канал В
const uint8_t PIN_L_A = 32;  // Левое колесо, канал А
const uint8_t PIN_L_B = 33;  // Левое колесо, канал В

// Коэффициенты по умолчанию для регуляторов (ПИ, скважность на м/с).
// Получены калибровкой tools/mtcal.py на роботе с поднятыми колёсами (lam 0.5) и проверены
// tools/steptest.py. Это заводские значения: они используются на пустом flash, а командами
