// Период контура скорости, мс (передаётся в uPID.setDt)
float DT = 10;

const double MAX_CONSTRUCTIVE_VELOCITY = 0.5; // м/сек

// === Энкодер и оценка скорости (speed_estimator.h) ===
// 270 меток на оборот вала редуктора, квадратура x4 -> 1080 фронтов на оборот
const float ENC_PPR = 270.0;
const float ENC_EDGES_PER_REV = ENC_PPR * 4.0;
// Левый энкодер считает "назад" при движении колеса вперёд (мотор зеркальный)
const float ENC_SIGN_R = 1.0;
const float ENC_SIGN_L = -1.0;
// Нет фронтов дольше этого времени - скорость 0. Фронт на 0.05 об/с приходит раз
// в 18.5 мс, поэтому ~3 интервала. Ниже ~0.015 об/с скорость читается как 0.
const uint32_t SPEED_TIMEOUT_US = 60000;
// Минимум фронтов в окне измерения. Выше ~0.2 об/с на такт приходится больше двух фронтов,
// и параметр ни на что не влияет. На низких скоростях окно растягивается на несколько
// тактов: 1 - максимум быстродействия, но у неидеальной квадратуры (сдвиг фаз не 90 град,
// скважность не 50%) интервалы между фронтами неравны, и скорость "рябит" (на моделе при
// неравенстве 10%: 11% СКО на 0.05 об/с). 2 убирает рябь в ~4 раза за один лишний интервал
// между фронтами (18 мс на 0.05 об/с), 4 (целая метка) - почти полностью, но окно 74 мс.
// Должно выполняться: SPEED_MIN_EDGES * (интервал фронтов на минимальной скорости) < SPEED_TIMEOUT_US.
const int32_t SPEED_MIN_EDGES = 2;
// |скорость| выше этого, об/с, считается помехой и отбрасывается
const float SPEED_MAX_SANE_REV_S = 6.0;
// Фильтр скорости на такте контура: 1.0 - выключен; 0.5 даёт tau ~ 14 мс при 100 Гц.
// Скользящее среднее на 5 значений из старой схемы убрано совсем.
const float SPEED_FILTER_K = 1.0;

// === Контур скорости: feedforward + ПИ ===
// Управление: u = sign(v_зад) * (FF_DEADZONE + FF_GAIN * |v_зад|) + ПИ(ошибка), u в [-1, 1]
// FF_DEADZONE - скважность ШИМ, с которой колесо вращается (трение движения), FF_GAIN -
// прирост скважности на 1 м/с. Значения откалиброваны в воздухе (mtcal.py); на полу
// мёртвая зона больше (около 0.3), и недостающее добирает интеграл ПИ.
float FF_DEADZONE_L = 0.1073;
float FF_DEADZONE_R = 0.1114;
float FF_GAIN_L = 0.5848;
float FF_GAIN_R = 0.9133;

// === Таймеры ===
// Контур скорости: 100 Гц. Оценка скорости использует реальные метки времени
// фронтов, поэтому джиттер такта на неё не влияет.
const unsigned long CONTROL_PERIOD_US = 10000; // мкс
// Одометрия считается и публикуется на 50 Гц
const unsigned long odom_timer_timeout = 20000; // мкс
// Аварийная остановка, если команды не приходят дольше 1 секунды
const unsigned int emergency_timer_timeout = 1000;
const unsigned int update_voltage_timer_timeout = 200;

// === I2C ===
// PCA9685 (ШИМ), INA219 и SSD1306 работают на 400 кГц. На 100 кГц обновление
// дисплея 128x32 занимает ~50 мс и срывало бы такты контура 100 Гц.
const uint32_t I2C_CLOCK_HZ = 400000;
// Медленные операции I2C (дисплей, INA219, проверка устройств) выполняются только
// если до следующего такта контура осталось не меньше этого времени, мкс.
const unsigned long I2C_WINDOW_MIN_US = 4000;

// === Телеметрия (команда $12) ===
// Пока включена, одометрия ($1) не публикуется: канал занят телеметрией на 100 Гц.
// Выключается сама, если команды не приходят дольше emergency_timer_timeout.
const uint8_t TELEMETRY_DECIMATION = 1; // 1 = каждый такт контура (100 Гц)


